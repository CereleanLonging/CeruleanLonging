export function headingExplanation(title: string, topic: string): string {
  const direct = helpByTitle.get(title);
  if (direct) return direct;
  if (/^继续配置/.test(title)) return "先关联项目目录，再回到接入管理选择对应角色。当前接入选择会保留，关联目录不调用模型。";
  if (/^(OpenAI|DeepSeek|Claude|Qwen|Kimi|A6API|Grok)\s+(API|Key)$/.test(title)) return topics.ProviderConnections;
  if (/^已登记项目检查程序/.test(title)) return "列出已登记的项目功能检查程序及参数定义，保存登记不执行检查。";
  if (/^已保存的计划/.test(title)) return "显示当前分页读取的本地计划；展开后可核对任务内容及批准状态。";
  if (/^项目累计上限/.test(title)) return "当前项目累计预算的上限；已有费用与预留一起计入，重新配置不会清零。";
  if (/^价格区间/.test(title)) return topics.ScopedCurrencyBudgetFields;
  if (topics[topic]) return topics[topic];
  if (/Currency|Charge/.test(topic)) return "核对这条项目费用记录的来源、金额与确认依据，历史确认不会覆盖原请求。";
  if (/Review|Startup|Recovery|Cancellation|Unsent|Advice/.test(topic)) return "核对所选原记录的身份、状态与处理依据。新的处理决定独立记录，不改写历史或自动重发任务。";
  if (/Verification/.test(topic)) return "查看所选提交的产物和阶段验收证据，原结果保留，复验与最终确认分别记录。";
  if (/Management/.test(topic)) return "查看这次指挥请求、回复和处理依据；未知请求保持待核对，不自动再次发送。";
  if (/Configuration/.test(topic)) return "查看当时保存的项目模型、目录和执行约束，原配置不会被当前编辑草稿覆盖。";
  if (/Jobs|Runs/.test(topic)) return "查看这次任务或运行的原始状态、尝试和结果，读取详情不会启动或重复执行。";
  return "查看本区的配置说明与当前记录；涉及保存、执行或确认的操作请使用对应按钮。";
}
