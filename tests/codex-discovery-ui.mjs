import { writeFile, mkdtemp } from "node:fs/promises";
import { resolve, join } from "node:path";
import assert from "node:assert/strict";
import { build } from "vite";
import { chromium } from "playwright-core";

const dir = await mkdtemp(resolve("reports/codex-discovery-ui-774-"));
const entry = join(dir, "entry.tsx");
await writeFile(entry, `import React from 'react';import {createRoot} from 'react-dom/client';import {flushSync} from 'react-dom';
import {CodexConnection} from '../../apps/desktop/src/CodexConnection';import {ErrorText,describeError} from '../../apps/desktop/src/ErrorText';
const root=createRoot(document.getElementById('root'));let epoch=0;window.commands=[];window.scans=[];window.describeError=describeError;
window.__TAURI_INTERNALS__={invoke:async (name,args)=>{if(name!=='scan_codex_installations')throw Error('Unexpected command');window.scans.push(args);return new Promise((resolve,reject)=>{window.completeScan=resolve;window.failScan=reject;});}};
window.show=(status=null)=>flushSync(()=>root.render(<CodexConnection key={++epoch} status={status} busy={false} connected={true} send={async c=>{window.commands.push(c);return true;}}/>));
window.showError=error=>flushSync(()=>root.render(<p role="alert"><ErrorText key={++epoch} error={error}/></p>));`);
await build({ configFile: false, logLevel: "error", define: { "process.env.NODE_ENV": JSON.stringify("production") }, oxc: { jsx: { runtime: "automatic" } }, build: { outDir: join(dir, "bundle"), emptyOutDir: false, lib: { entry, name: "CodexDiscoveryUI", formats: ["iife"], fileName: () => "ui.js" } } });
const candidate = { executable: "E:\\WindowsApps\\OpenAI.Codex_1_x64\\app\\resources\\codex.exe", directory: "E:\\WindowsApps\\OpenAI.Codex_1_x64\\app\\resources", source: "正在运行的 Codex" };
let browser;
const cases = [], errors = [];
try {
  browser = await chromium.launch({ executablePath: "C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe", headless: true });
  const page = await browser.newPage({ viewport: { width: 1100, height: 900 } });
  page.on("pageerror", e => errors.push(String(e)));
  await page.setContent('<html><meta charset="utf-8"><div id="root"></div></html>');
  await page.addStyleTag({ path: resolve("apps/desktop/src/style.css") });
  await page.addScriptTag({ path: join(dir, "bundle/ui.js") });
  await page.evaluate(() => window.show());
  await page.getByLabel("Codex 程序完整路径").fill("E:\\WindowsApps");
  await page.getByRole("button", { name: "扫描本地 Codex", exact: true }).click();
  assert.equal(await page.getByRole("button", { name: "正在扫描…", exact: true }).isDisabled(), true);
  assert.equal(await page.getByLabel("Codex 程序完整路径").isDisabled(), true);
  assert.equal(await page.getByRole("button", { name: "测试连通", exact: true }).isDisabled(), true);
  assert.deepEqual(await page.evaluate(() => window.scans), [{ hint: "E:\\WindowsApps" }]);
  await page.evaluate(candidate => window.completeScan({ candidates: [candidate], warnings: [], limited: false }), candidate);
  await page.getByText("找到 1 个候选程序", { exact: false }).waitFor();
  assert.equal(await page.getByLabel("Codex 程序完整路径").inputValue(), "E:\\WindowsApps");
  assert.equal(await page.evaluate(() => window.commands.length), 0);
  cases.push("Scan is read-only, serialized, and does not change the chosen path or check login");
  await page.getByRole("button", { name: "使用此路径", exact: true }).click();
  assert.equal(await page.getByLabel("Codex 程序完整路径").inputValue(), candidate.executable);
  assert.equal(await page.evaluate(() => window.commands.length), 0);
  await page.screenshot({ path: join(dir, "scan-results.png"), fullPage: true });
  await page.getByRole("button", { name: "测试连通", exact: true }).click();
  assert.deepEqual(await page.evaluate(() => window.commands), [{ type: "checkCodex", executable: candidate.executable }]);
  cases.push("Candidate selection is separate from the single explicit login check");
  await page.getByRole("button", { name: "扫描本地 Codex", exact: true }).click();
  await page.evaluate(() => window.completeScan({ candidates: [], warnings: ["部分安装目录无读取权限，已跳过。"], limited: false }));
  await page.getByText("本次扫描未找到可用程序", { exact: false }).waitFor();
  assert.equal(await page.getByLabel("Codex 程序完整路径").inputValue(), candidate.executable);
  cases.push("No results preserve manual input and show skipped-directory information");
  await page.getByRole("button", { name: "扫描本地 Codex", exact: true }).click();
  await page.evaluate(() => window.failScan("Access is denied. (os error 5)"));
  await page.getByText("访问被拒绝", { exact: false }).waitFor();
  assert.equal(await page.getByRole("button", { name: "扫描本地 Codex", exact: true }).isEnabled(), true);
  cases.push("A failed scan shows a Chinese error and releases the UI lock");
  await page.evaluate(() => window.show({ executable: "C:\\codex.exe", state: "checking", checkedAt: "2026-11-03T00:00:00Z", models: [], error: null }));
  assert.equal(await page.getByRole("button", { name: "扫描本地 Codex", exact: true }).isDisabled(), true);
  cases.push("Scanning cannot race a connection check");
  await page.evaluate(() => window.show({ executable: "C:\\old\\codex.exe", state: "available", checkedAt: "2026-11-03T00:00:00Z", models: ["old-model"], error: null }));
  await page.getByLabel("Codex 程序完整路径").fill("E:\\new\\codex.exe");
  await page.getByText("路径已更改，需重新检查", { exact: true }).waitFor();
  assert.equal(await page.getByText("可用模型：old-model", { exact: true }).count(), 0);
  cases.push("Changing the executable invalidates the displayed connection result");
  await page.evaluate(() => window.showError("linked or invalid host path"));
  assert.equal(await page.getByRole("alert").innerText(), "路径类型不正确或使用了链接。请选择实际文件；需要程序路径时，请填写完整的 .exe 路径。 技术详情");
  await page.getByRole("button", { name: "技术详情", exact: true }).click();
  assert.equal(await page.getByText("linked or invalid host path", { exact: true }).count(), 1);
  await page.screenshot({ path: join(dir, "translated-error.png"), fullPage: true });
  assert.match(await page.evaluate(() => window.describeError("Codex observation timeout; result unknown").message), /结果尚未确认/);
  assert.deepEqual(await page.evaluate(() => window.describeError("当前填写的是文件夹")), { message: "当前填写的是文件夹", detail: null });
  assert.equal(await page.evaluate(() => window.describeError("unrecognized backend error").detail), "unrecognized backend error");
  cases.push("Chinese diagnostics preserve unknown-result semantics and original technical details");
  await page.evaluate(() => window.show());
  await page.getByRole("button", { name: "扫描本地 Codex", exact: true }).click();
  await page.evaluate(candidate => window.completeScan({ candidates: [candidate], warnings: [], limited: false }), candidate);
  await page.getByRole("button", { name: "使用此路径", exact: true }).waitFor();
  await page.setViewportSize({ width: 390, height: 844 });
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  await page.screenshot({ path: join(dir, "narrow-results.png"), fullPage: true });
  assert.deepEqual(errors, []);
  await writeFile(join(dir, "result.json"), JSON.stringify({ passed: true, cases, errors, scope: "Offline production components; mocked scan; no provider calls" }, null, 2));
  console.log(JSON.stringify({ passed: true, cases: cases.length, report: dir }));
} catch (e) {
  await writeFile(join(dir, "failure.json"), JSON.stringify({ error: String(e), cases, errors }, null, 2));
  throw e;
} finally { await browser?.close(); }
