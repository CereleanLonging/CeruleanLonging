import assert from 'node:assert/strict';
import {spawn} from 'node:child_process';
import {once} from 'node:events';
import {createServer} from 'node:net';
import {mkdir,mkdtemp,readFile,writeFile} from 'node:fs/promises';
import {join,resolve} from 'node:path';
import {chromium} from 'playwright-core';
import {openConnectionMethod,deferModelChoice} from './connection-ui-helpers.mjs';

assert.equal(process.env.CERULEAN_NATIVE_OWNED_JOB,'1');
const run=await mkdtemp(resolve('reports/credential-actions-native-'));
assert(process.env.CERULEAN_CACHE_SESSION,'Use managed cache runner');
const webview=join(process.env.CERULEAN_CACHE_SESSION,'credential-actions-webview');
const data=join(run,'data'), project=join(run,'project');
await mkdir(project);
const marker='synthetic-offline-credential-actions';
const wait=async predicate=>{for(let n=0;n<160;n++){const value=await predicate();if(value)return value;await new Promise(r=>setTimeout(r,150));}throw Error('Credential state timeout');};
const server=createServer();server.listen(0,'127.0.0.1');await once(server,'listening');const port=server.address().port;await new Promise(r=>server.close(r));
const app=spawn(process.env.CERULEAN_NATIVE_GUI,[],{windowsHide:true,stdio:'ignore',env:{...process.env,CERULEAN_TEST_DATA_DIR:data,CERULEAN_TEST_WEBVIEW_ROOT:webview,CERULEAN_TEST_ACCESS_ROOT:join(run,'settings'),CERULEAN_TEST_MAINTENANCE_ROOT:join(run,'maintenance'),WEBVIEW2_ADDITIONAL_BROWSER_ARGUMENTS:`--remote-debugging-port=${port} --remote-debugging-address=127.0.0.1`}});
let browser,page;
const cases=[];
const invoke=(name,args)=>page.evaluate(({name,args})=>window.__TAURI_INTERNALS__.invoke(name,args),{name,args});
const snapshot=()=>invoke('core_request',{command:{type:'snapshot'}});
try{
  browser=await wait(async()=>{try{return await chromium.connectOverCDP(`http://127.0.0.1:${port}`,{timeout:500});}catch{return null;}});
  page=await wait(()=>browser.contexts().flatMap(c=>c.pages()).find(p=>p.url().includes('tauri.localhost')));
  page.setDefaultTimeout(12000);
  await page.getByText('本地核心已连接',{exact:true}).waitFor();
  await page.locator('.sidebar nav').getByRole('button',{name:'接入管理',exact:false}).click();
  const chief=page.getByRole('region',{name:'主指挥',exact:true});
  await openConnectionMethod(page,'主指挥','key');
  await chief.getByLabel('凭证供应商',{exact:true}).selectOption('a6api');
  await chief.getByLabel('A6API API Key',{exact:true}).fill(marker);
  await chief.getByRole('button',{name:'加密保存 A6API Key',exact:true}).click();
  await deferModelChoice(page);
  await wait(async()=>!(await chief.getByRole('button',{name:'删除本机 A6API Key',exact:true}).isDisabled()));
  assert.equal(await chief.getByRole('button',{name:'测试连通',exact:true}).isDisabled(),false);
  assert.equal((await snapshot()).providerConnections.find(p=>p.provider==='a6api').keyConfigured,true);
  const encrypted=await readFile(join(data,'credentials/a6api.dpapi'));
  assert(!encrypted.includes(Buffer.from(marker)));
  await chief.getByRole('status').filter({hasText:'A6API Key 已加密保存'}).waitFor();
  cases.push('Unbound credential save enables delete and test using the real command receipt and refreshed snapshot');
  await chief.getByLabel('A6API API Key',{exact:true}).fill('synthetic-unsaved-replacement');
  assert.equal(await chief.getByRole('button',{name:'测试连通',exact:true}).isDisabled(),true);
  await chief.getByRole('status').filter({hasText:'输入的新 Key 尚未保存'}).waitFor();
  assert.deepEqual(await readFile(join(data,'credentials/a6api.dpapi')),encrypted);
  await chief.getByLabel('A6API API Key',{exact:true}).fill('');
  assert.equal(await chief.getByRole('button',{name:'测试连通',exact:true}).isDisabled(),false);
  cases.push('An unsaved replacement cannot test the prior saved key; clearing the draft restores the saved-key test');
  const saveBox=await chief.getByRole('button',{name:'加密保存 A6API Key',exact:true}).boundingBox();
  const deleteBox=await chief.getByRole('button',{name:'删除本机 A6API Key',exact:true}).boundingBox();
  assert(Math.abs(saveBox.y-deleteBox.y)<1&&Math.abs(saveBox.height-deleteBox.height)<1);
  await chief.getByLabel('A6API API Key',{exact:true}).fill('invalid whitespace credential');
  await chief.getByRole('button',{name:'加密保存 A6API Key',exact:true}).click();
  await chief.getByRole('alert').filter({hasText:'不能带空格或换行'}).waitFor();
  assert.deepEqual(await readFile(join(data,'credentials/a6api.dpapi')),encrypted);
  assert.equal(await chief.getByRole('button',{name:'测试连通',exact:true}).isDisabled(),false);
  cases.push('Save and delete align; a rejected replacement displays its real error beside the buttons and preserves the old key');
  await chief.getByRole('button',{name:'删除本机 A6API Key',exact:true}).click();
  await wait(async()=>(await snapshot()).providerConnections.find(p=>p.provider==='a6api').keyConfigured===false);
  assert.equal(await chief.getByRole('button',{name:'测试连通',exact:true}).isDisabled(),true);
  cases.push('Delete clears encrypted credentials and disables testing');
  await chief.getByLabel('凭证供应商',{exact:true}).selectOption('openai');
  await chief.getByLabel('OpenAI API Key',{exact:true}).fill(marker);
  await chief.getByRole('button',{name:'加密保存 Key',exact:true}).click();
  await deferModelChoice(page);
  await chief.getByRole('status').filter({hasText:'OpenAI Key 已加密保存'}).waitFor();
  assert.equal(await chief.getByRole('button',{name:'测试连通',exact:true}).isDisabled(),false);
  await chief.getByRole('button',{name:'删除本机 Key',exact:true}).click();
  await chief.getByRole('status').filter({hasText:'OpenAI Key 已从本机删除'}).waitFor();
  assert.equal(await chief.getByRole('button',{name:'测试连通',exact:true}).isDisabled(),true);
  cases.push('OpenAI shares the confirmed save/delete feedback and enabled-state behavior');
  await invoke('core_submit',{command:{type:'registerProject',project:{id:'fixture',root:project,timezone:'UTC'}}});
  await page.locator('.sidebar nav').getByRole('button',{name:'需求与计划',exact:false}).click();
  await page.locator('.sidebar nav').getByRole('button',{name:'接入管理',exact:false}).click();
  await page.locator('.project-connections').waitFor();
  assert.equal(await page.locator('#planning-chief-directory').evaluate(input=>input.readOnly),true);
  assert.equal((await page.locator('#planning-chief-directory').inputValue()).replace(/^\\\\\?\\/,''),project+'-chief');
  cases.push('Native project configuration binds its generated chief directory as read-only');
  await openConnectionMethod(page,'副指挥','api');
  await page.locator('#planning-deputy-source').selectOption('provider:a6ApiVip');
  await openConnectionMethod(page,'副指挥','key');
  const deputy=page.getByRole('region',{name:'副指挥',exact:true});
  await deputy.getByLabel('A6API API Key',{exact:true}).fill(marker);
  await deputy.getByRole('button',{name:'加密保存 A6API Key',exact:true}).click();
  await deferModelChoice(page);
  await wait(async()=>!(await deputy.getByRole('button',{name:'删除本机 A6API Key',exact:true}).isDisabled()));
  assert.equal(await deputy.getByRole('button',{name:'测试连通',exact:true}).isDisabled(),false);
  cases.push('Project-scoped Key form independently saves and refreshes its configured provider');
  await deputy.screenshot({path:join(run,'credential-actions.png')});
  // Corrupt only this synthetic DPAPI envelope. The actual probe stops during
  // decryption, before constructing an HTTP request or reading a real credential.
  await writeFile(join(data,'credentials/a6api.dpapi'),'invalid encrypted fixture');
  await deputy.getByRole('button',{name:'测试连通',exact:true}).click();
  await deputy.getByRole('alert').filter({hasText:'本机凭证加解密失败'}).waitFor();
  assert.equal((await snapshot()).providerConnections.find(p=>p.provider==='a6api').state,'failed');
  cases.push('The enabled test button reaches the real asynchronous probe and reports local decryption failure without network access');
  await deputy.getByRole('button',{name:'删除本机 A6API Key',exact:true}).click();
  await wait(async()=>(await snapshot()).providerConnections.find(p=>p.provider==='a6api').keyConfigured===false);
  await page.getByRole('button',{name:'退出工作台',exact:true}).click();
  await page.getByRole('button',{name:'确认退出并停止后台',exact:true}).click();
  await wait(()=>app.exitCode!==null);
  const result={status:'passed',cases,run,providerCalls:0,syntheticCredentialsOnly:true};
  await writeFile(join(run,'result.json'),JSON.stringify(result,null,2));console.log(JSON.stringify(result));
}catch(error){
  const current=await snapshot().catch(()=>null);
  const diagnostic={error:String(error),cases,credentials:current?.providerConnections,alerts:await page?.getByRole('alert').allTextContents()};
  await page?.screenshot({path:join(run,'failure.png')}).catch(()=>{});
  await writeFile(join(run,'failure.json'),JSON.stringify(diagnostic,null,2));throw error;
}finally{
  if(app.exitCode===null&&page&&!page.isClosed())await invoke('close_workbench').catch(()=>{});
  await browser?.close().catch(()=>{});
  await wait(()=>app.exitCode!==null);
}
